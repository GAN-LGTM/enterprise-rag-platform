async def seed_if_empty(container) -> int:
    """把演示文档灌进向量库。已存在内容则跳过。"""
    if container.store_mode != "memory":
        return 0

    from ..ingest.chunker import chunk_text
    from ..ingest.version_store import register_seed_version
    from ..retrieval.store import Chunk

    total = 0
    for dept_id, docs in DEMO_DOCS.items():
        for doc_name, content in docs.items():
            texts = chunk_text(content, size=300, overlap=60)
            chunks = [
                Chunk(id=None, department_id=dept_id, chunk_text=t, doc_name=doc_name,
                      page_num=None, chunk_index=i, version=1,
                      metadata={"source": "demo-seed"})
                for i, t in enumerate(texts)
            ]
            vecs = [container.embedder.embed_sync(c.chunk_text) for c in chunks]
            await container.store.add_chunks(chunks, vecs)
            register_seed_version(doc_name, dept_id, len(chunks),
                                  hashlib.md5(content.encode("utf-8")).hexdigest())
            total += len(chunks)

    log.info("seed.done", chunks=total, departments=len(DEMO_DOCS))
    return total
