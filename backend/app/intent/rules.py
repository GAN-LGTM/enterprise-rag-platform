"""
第一层：硬规则匹配（正则 / 关键词）。

特点：0ms、零成本、覆盖约 80%、准确率约 95%。命中即直接决定路由，不进 LLM。

规则按优先级从高到低排列，先命中先返回。排布原则：
  1) 越"贵"的误判代价越大越靠前——操作型点错了会误触发流程，所以最高优先；
  2) 点名部门（cross_dept）排在业务词之前，否则"市场部费用"会被业务规则吃掉，
     而跨部门必须过权限门；
  3) 强数据信号（对比/同比/排名/多少）排在业务名词之前，
     否则"各区域销售额对比"会被"销售额"判成普通业务问答；
  4) 通用制度（public_kb）排在部门业务（dept_kb）之前，
     因为制度词更具体（"劳动合同" vs "合同"），反过来会吞掉制度类问题。

持续迭代：判定结果全部落在 data/intent_log.jsonl，
定期用 scripts/intent_report.py 找出漏网词补进本文件，让 L1 覆盖率逐步升高。
"""
