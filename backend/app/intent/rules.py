def match_rule_detail(query: str) -> tuple[str, float, str, str] | None:
    """返回 (intent, confidence, note, matched_text)；未命中返回 None。"""
    for rule in RULES:
        m = rule.pattern.search(query)
        if m:
            return rule.intent, 0.95, rule.note, m.group(0)
    return None


def match_rule(query: str) -> tuple[str, float, str] | None:
    """返回 (intent, confidence, note) 或 None（兼容旧调用方）。"""
    hit = match_rule_detail(query)
    return (hit[0], hit[1], hit[2]) if hit else None


def extract_target_depts(query: str) -> list[str]:
    """从问题里抽取被点名的部门 ID（用于 cross_dept 权限校验）。"""
    hits, seen = [], set()
    # 长别名优先匹配，避免"人力资源部"被"人力"截断成同样结果后重复
    for alias in sorted(DEPT_ALIAS, key=len, reverse=True):
        dept_id = DEPT_ALIAS[alias]
        if alias in query and dept_id not in seen:
            seen.add(dept_id)
            hits.append(dept_id)
    return hits


def has_action_marker(query: str) -> bool:
    """句里是否存在显式动作词（L4 判 operation 时的佐证，缺证即降级）。"""
    return any(m in query for m in ACTION_MARKERS)
